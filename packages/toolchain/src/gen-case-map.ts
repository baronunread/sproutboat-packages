export {};
// Simple (one code unit to one code unit) BMP case mappings as runs: [start, end, delta, step].
function runs(map: (c: string) => string) {
  const pairs: [number, number][] = [];
  for (let cp = 0x80; cp <= 0xffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    const ch = String.fromCharCode(cp),
      m = map(ch);
    if (m.length === 1 && m !== ch) pairs.push([cp, m.charCodeAt(0) - cp]);
  }
  const out: number[][] = [];
  for (const [cp, d] of pairs) {
    const last = out[out.length - 1];
    if (
      last &&
      last[2] === d &&
      (last[3] === 0 ? cp - last[1] === 1 || cp - last[1] === 2 : cp - last[1] === last[3])
    ) {
      if (last[3] === 0) last[3] = cp - last[1];
      last[1] = cp;
    } else out.push([cp, cp, d, 0]);
  }
  return out.map((r) => [r[0], r[1], r[2], r[3] || 1]);
}
const lower = runs((c) => c.toLowerCase()),
  upper = runs((c) => c.toUpperCase());
console.log("lower runs", lower.length, "upper runs", upper.length);
const all = [...lower, ...upper];
// usage: bun gen-case-map.ts case-map.ts
console.log(
  "delta range",
  Math.min(...all.map((r) => r[2])),
  Math.max(...all.map((r) => r[2])),
  "max end",
  Math.max(...all.map((r) => r[1]).map(Number)).toString(16),
);
const enc = (rs: number[][]) =>
  rs.map(([s, e, d, st]) => [s, e, s + d, st].map((x) => "\\u" + x.toString(16).padStart(4, "0")).join("")).join("");
if (process.argv[2])
  await Bun.write(
    process.argv[2],
    `/**
 * Unicode simple case mappings for BMP code units (one unit to one unit), generated by
 * gen-case-map.ts from ${"Bun " + Bun.version}'s String.prototype.toLowerCase/toUpperCase and checked
 * in, so patched builds do not depend on the patching engine's Unicode version. Runs of four
 * UTF-16 code units: start, end, the start's mapping, step (1, or 2 for alternating pairs);
 * a unit in a run maps to that mapping plus its distance from the start.
 */
export const CASE_LOWER_RUNS = "${enc(lower)}";
export const CASE_UPPER_RUNS = "${enc(upper)}";
`,
  );
