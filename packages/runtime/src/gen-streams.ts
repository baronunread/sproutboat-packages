import { readFile, writeFile } from "node:fs/promises";

const marker = "// WEB STREAMS: generated by gen-streams.ts, do not edit.";
const endMarker = "// END WEB STREAMS";
const result = await Bun.build({
  entrypoints: [`${import.meta.dir}/streams-entry.js`],
  target: "browser",
  format: "iife",
  minify: false,
});
if (!result.success) throw new Error(result.logs.join("\n"));
let code = await result.outputs[0].text();
// Porffor cannot resolve controller class prototypes captured by an IIFE.
// Keep these classes at module scope. User modules have their own scope.
if (!code.startsWith("(() => {") || !code.trimEnd().endsWith("})();")) {
  throw new Error("Unexpected streams bundle format");
}
code = code.slice("(() => {".length).trimEnd().slice(0, -"})();".length);
// streams-entry.js installs each class with its own static assignment (see there).
const exported = Object.keys(await import("web-streams-polyfill"));
const missing = exported.filter((name) => !code.includes(`globalThis.${name} = `));
if (!exported.length || missing.length) throw new Error(`streams-entry.js does not install: ${missing.join(", ") || "(no exports found)"}`);
code = code.replace(/^\s*\/\/ .*streams-entry.js$/m, "// streams-entry.js");
code = code.replace(/^\s*\/\/ .*web-streams-polyfill\/dist\/ponyfill.mjs$/m,
  "// web-streams-polyfill 4.3.0, MIT, copyright Mattias Buelens (see WEB_STREAMS_LICENSE)");
const path = `${import.meta.dir}/native-fetch-prelude.js`;
let prelude = await readFile(path, "utf8");
const start = prelude.indexOf(marker);
if (start !== -1) {
  const end = prelude.indexOf(endMarker, start);
  if (end === -1) throw new Error("Missing streams block end marker");
  prelude = prelude.slice(0, start) + prelude.slice(end + endMarker.length).replace(/^\n+/, "");
}
await writeFile(path, `${marker}\n/* oxlint-disable -- generated third-party implementation */\n${code}\n/* oxlint-enable */\n${endMarker}\n\n${prelude}`);
