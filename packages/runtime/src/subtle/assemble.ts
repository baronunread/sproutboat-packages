// Builds the C that crypto.subtle compiles into an embedded sprout: Monocypher (vendored verbatim in
// vendor/) plus subtle.c, adapted for the one place it is compiled.
//
// Porffor splits inline C into a shared header and per-unit implementation files, and the splitter
// is a small scanner, not a C parser. Three things follow, and this file handles each:
//   - A comment that opens a top-level chunk makes the chunk look like a variable and breaks the
//     split, so every comment is removed (the licence travels in vendor/ and the README).
//   - A top-level non-const static function becomes a global symbol in its unit, so every file-scope
//     name Monocypher declares static is aliased to a prefixed one by the preprocessor, for the span
//     of the file. Its short typedef names (u8, fe) and macros (FOR, MIN) are aliased or undefined
//     the same way, so none of them reaches the rest of the translation unit, which also holds
//     Porffor's generated code and SQLite glue.
//   - Preprocessor lines are copied to both halves in order, so the aliases hold on both sides.
import { readFileSync, writeFileSync } from "node:fs";

const here = (name: string) => new URL(name, import.meta.url);
const read = (name: string) => readFileSync(here(name), "utf8");

/** Monocypher's internal typedef names. Each is aliased by the preprocessor across the whole block. */
const INTERNAL_NAMES = ["i8", "u8", "i16", "u32", "i32", "i64", "u64", "fe", "ge", "ge_cached", "ge_precomp", "blk"];

export const SUBTLE_BEGIN =
  "// SUBTLE:BEGIN (generated by `bun run gen:subtle`; edit src/subtle/subtle.c, not this block)";
export const SUBTLE_END = "// SUBTLE:END";

/** Removes C comments, leaving strings and character constants alone. */
export function stripComments(source: string): string {
  let out = "";
  for (let i = 0; i < source.length;) {
    const c = source[i];
    if (c === '"' || c === "'") {
      let j = i + 1;
      while (source[j] !== c) j += source[j] === "\\" ? 2 : 1;
      out += source.slice(i, j + 1);
      i = j + 1;
    } else if (c === "/" && source[i + 1] === "/") {
      while (i < source.length && source[i] !== "\n") i++;
    } else if (c === "/" && source[i + 1] === "*") {
      i = source.indexOf("*/", i + 2) + 2;
      out += " ";
    } else {
      out += c;
      i++;
    }
  }
  return out;
}

const tidy = (source: string) =>
  stripComments(source)
    .split("\n")
    .map((line) => line.replace(/\s+$/, ""))
    .filter((line, index, all) => line !== "" || (index > 0 && all[index - 1] !== ""))
    .join("\n");

export function assembleSubtleC(): string {
  // The C++ guards (a namespace, extern "C") would swallow the rest of the block in the splitter.
  const strip = (name: string) =>
    tidy(read(name))
      .replace(/^#include "monocypher[^"]*"\s*$/gm, "")
      .replace(/^#ifdef (?:MONOCYPHER_CPP_NAMESPACE|__cplusplus)\n[\s\S]*?^#endif\n/gm, "");
  // Each vendored .c file was written to be its own translation unit: its macros end with it, and
  // its static names get a prefix of their own (both define `hash_reduce`, differently).
  const unit = (name: string, index: number) => {
    const body = strip(name);
    const macros = [...new Set([...body.matchAll(/^#define\s+(\w+)/gm)].map((m) => m[1]))];
    const statics = [
      ...new Set([...body.matchAll(/^static\b([^;{(=]*?)\b(\w+)\s*(?:\(|\[|=|;)/gm)].map((m) => m[2])),
    ].filter((n) => !INTERNAL_NAMES.includes(n));
    return [
      ...statics.map((n) => `#define ${n} sbm${index}_${n}`),
      body,
      ...macros.map((n) => `#undef ${n}`),
      ...statics.map((n) => `#undef ${n}`),
    ].join("\n");
  };
  const headers = ["vendor/monocypher.h", "vendor/monocypher-ed25519.h"].map(strip).join("\n");
  const alias = INTERNAL_NAMES.map((n) => `#define ${n} sbm_${n}`).join("\n");
  const unalias = INTERNAL_NAMES.map((n) => `#undef ${n}`).join("\n");
  return [
    "// Monocypher 4.0.2 (BSD-2-Clause OR CC0-1.0), Loup Vaillant: vendor/monocypher*.[ch] without comments.",
    alias,
    headers,
    unit("vendor/monocypher.c", 1),
    unit("vendor/monocypher-ed25519.c", 2),
    unalias,
    "// End of Monocypher.",
    tidy(read("subtle.c")),
  ].join("\n");
}

/**
 * One call into sbc_op. `op` is a decimal string; a, b, c, d are byte strings (latin1, one char per
 * byte). Returns a byte string whose first byte is the status (0 ok, 1 DataError, 2 OperationError,
 * 3 NotSupportedError) and whose rest is the result. Sits inside the markers so that pruning the
 * block (wrap.ts, for a handler that never touches crypto.subtle) removes it with the C it calls.
 */
const SUBTLE_RAW = `// oxlint-disable-next-line no-unused-vars -- read inside the RawC block below, not by JS.
function __sbSubtleRaw(op, a, b, c, d) {
  let out = "";
  // oxlint-disable-next-line no-unused-expressions -- Porffor.c\`...\` is inline C the compiler consumes, not a JS expression.
  Porffor.c\`
    const char* __os; size_t __osl; char* __oso = 0;
    porf_native_fetch_read_value(op, &__os, &__osl, &__oso);
    char __ob[8]; size_t __ok = __osl < 7 ? __osl : 7;
    memcpy(__ob, __os, __ok); __ob[__ok] = 0;
    if (__oso) free(__oso);
    int __op = atoi(__ob);

    const char* __pa = ""; size_t __pal = 0; porf_native_fetch_read_raw_bytes(a, &__pa, &__pal);
    const char* __pb = ""; size_t __pbl = 0; porf_native_fetch_read_raw_bytes(b, &__pb, &__pbl);
    const char* __pc = ""; size_t __pcl = 0; porf_native_fetch_read_raw_bytes(c, &__pc, &__pcl);
    const char* __pd = ""; size_t __pdl = 0; porf_native_fetch_read_raw_bytes(d, &__pd, &__pdl);
    unsigned char* __res = 0; size_t __resl = 0;
    int __rc = sbc_op(__op, (const unsigned char*)__pa, __pal, (const unsigned char*)__pb, __pbl,
                      (const unsigned char*)__pc, __pcl, (const unsigned char*)__pd, __pdl, &__res, &__resl);
    unsigned char* __w = (unsigned char*)malloc(__resl + 1);
    if (__w) {
      __w[0] = (unsigned char)__rc;
      if (__resl) memcpy(__w + 1, __res, __resl);
      out = porf_box((f64)porf_native_fetch_alloc_bytestring((const char*)__w, __resl + 1), 195);
      free(__w);
    }
    free(__res);
  \`;
  return out;
}
`;

/** The transport with the generated block (re)written between its markers. */
export function spliceSubtle(transport: string): string {
  const start = transport.indexOf(SUBTLE_BEGIN);
  const end = transport.indexOf(SUBTLE_END);
  if (start < 0 || end < start) throw new Error("transport-embedded.js has no SUBTLE markers");
  const block = assembleSubtleC();
  if (/`|\$\{/.test(block)) throw new Error("subtle C contains a backtick or ${: it is spliced into a JS template");
  return (
    transport.slice(0, start) +
    SUBTLE_BEGIN +
    "\n// oxlint-disable-next-line no-unused-expressions -- Porffor.c`...` is inline C the compiler consumes, not a JS expression.\nPorffor.c`\n" +
    block +
    "\n`;\n" +
    SUBTLE_RAW +
    transport.slice(end)
  );
}

if (import.meta.main) {
  const path = new URL("../transport-embedded.js", import.meta.url);
  writeFileSync(path, spliceSubtle(readFileSync(path, "utf8")));
}
